package fever

// The bolt codes of Fever, `↯/f.15` and `↯/f.16`: the subdivisions of the letter Fever shares
// with Pyrocosm and its other tools (`pyrocosm.Bolts`), one for each of Fever's modules. The
// record of what every code means is `bolt.tel` in propensive/pyrocosm.
object FeverBolts:
  final val core     = 15
  final val launcher = 16

  // The code of the `error`th error of Fever's core, or of its `variant`th variant.
  def apply(error: Int, variant: Int = 0): fulminate.Bolt =
    pyrocosm.Bolts(core, error, variant)

  // Errors 1 and 2 are `Launch.Error` and `Script.Error`. The rest are failures Fever reports
  // other than through an error type, each printed after its code's label: a script which is
  // not resident when `stop` names it; a compiler which crashed rather than finishing; a
  // throwable no status anticipates, which is a bug in Fever; a subcommand not yet implemented;
  // and a command line which was not understood.
  final val notResident   = 3
  final val compilerCrash = 4
  final val unanticipated = 5
  final val unimplemented = 6
  final val usage         = 7
